import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import { observeHubConnection } from '../src/services/connection';
const { probeHub, readHubPreference, saveHubPreference } = vi.hoisted(() => ({ probeHub:vi.fn(), readHubPreference:vi.fn(), saveHubPreference:vi.fn() }));
vi.mock('../src/services/api', () => ({ probeHub }));
vi.mock('../src/services/settings', () => ({ readHubPreference, saveHubPreference }));
const hub = { name:'Room', ip:'192.168.1.50', http_port:8080, ws_port:8085 };
beforeEach(() => { vi.useFakeTimers(); readHubPreference.mockReturnValue(null); saveHubPreference.mockReturnValue(true); });
afterEach(() => { vi.useRealTimers(); vi.resetAllMocks(); });
it('automatically probes an initial candidate and preserves reachability without discovery', async () => {
  probeHub.mockResolvedValue(true);
  const update=vi.fn(), connection=observeHubConnection(update);
  connection.discovered([hub]);
  await vi.advanceTimersByTimeAsync(0);
  expect(update).toHaveBeenLastCalledWith({ status:'connected',hub,persisted:true });
  connection.discovered([]);
  await vi.advanceTimersByTimeAsync(3000);
  expect(update).toHaveBeenLastCalledWith({ status:'connected',hub,persisted:true });
  expect(probeHub).toHaveBeenCalledTimes(2);
  connection.stop();
});
it('reconnects a saved/manual Hub after network loss without discovery', async () => {
  readHubPreference.mockReturnValue(hub);
  probeHub.mockResolvedValueOnce(false).mockResolvedValue(true);
  const update=vi.fn(), connection=observeHubConnection(update);
  await vi.advanceTimersByTimeAsync(0);
  expect(update).toHaveBeenLastCalledWith({ status:'offline',hub,persisted:true });
  await vi.advanceTimersByTimeAsync(1000);
  expect(update).toHaveBeenLastCalledWith({ status:'connected',hub,persisted:true });
  connection.stop();
});
it('ignores obsolete selection results and aborts on cleanup', async () => {
  const results: ((value:boolean)=>void)[]=[];
  probeHub.mockImplementation(() => new Promise(resolve => results.push(resolve)));
  const update=vi.fn(), connection=observeHubConnection(update);
  connection.select(hub);
  const second={...hub, ip:'192.168.1.51'};
  connection.select(second);
  results[0](true); await vi.advanceTimersByTimeAsync(0);
  expect(saveHubPreference).not.toHaveBeenCalled();
  results[1](true); await vi.advanceTimersByTimeAsync(0);
  expect(saveHubPreference).toHaveBeenCalledWith(second);
  connection.stop();
  const calls=probeHub.mock.calls.length;
  await vi.advanceTimersByTimeAsync(30_000);
  expect(probeHub).toHaveBeenCalledTimes(calls);
  expect(probeHub.mock.calls[1][1].aborted).toBe(true);
});
it('keeps a verified session usable if preference storage fails and never overlaps retries', async () => {
  saveHubPreference.mockReturnValue(false); probeHub.mockResolvedValue(true);
  const update=vi.fn(), connection=observeHubConnection(update);
  connection.select(hub); await vi.advanceTimersByTimeAsync(0);
  expect(update).toHaveBeenLastCalledWith({ status:'connected',hub,persisted:false });
  let complete!: (value:boolean)=>void;
  probeHub.mockImplementation(() => new Promise(resolve => {complete=resolve;}));
  await vi.advanceTimersByTimeAsync(30_000);
  expect(probeHub).toHaveBeenCalledTimes(2);
  complete(false); await vi.advanceTimersByTimeAsync(0);
  expect(update).toHaveBeenLastCalledWith({ status:'offline',hub,persisted:false });
  connection.stop();
});
