#!/usr/bin/env python3
"""Builds prototype/index.html (the full-window Home, Stream and quiz prototype) from the remake screen in
design-system/showcase.html, so the two never drift. `--check` fails when the file is stale."""
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SHOWCASE = ROOT / "design-system" / "showcase.html"
OUT = ROOT / "prototype" / "index.html"
KEEP = re.compile(r"^(\*|body|\.doc-brand-badge|\.btn|\.badge|\.avatar|\.form-input|textarea\.form-input|\.segmented|\.seg-item|\.cr-switch|\.cr-icon|\.cr-link|\.cr-spacer|\.cr-item|\.tile|\.rm|@container rm)")

EXTRA_CSS = """html, body { height: 100%; }
.rm { min-height: 100vh; border: none; border-radius: 0; }
.rm-sheet { min-height: calc(100vh - 64px); padding-bottom: 96px; }
.rm-modal { position: fixed; }
.pv-bar { position: fixed; left: 50%; bottom: 16px; transform: translateX(-50%); z-index: 20; display: flex; gap: 8px; align-items: center; flex-wrap: wrap; justify-content: center; padding: 8px 12px; border-radius: var(--radius-xl); background: var(--color-surface-white); border: 1px solid var(--color-border); box-shadow: var(--shadow-elevated); max-width: calc(100vw - 32px); }
.pv-bar .cr-switch { margin: 0; }
"""

BOOT = """const app = document.getElementById('app');
app.innerHTML = rmApp();
const rm = app.querySelector('.rm');
/* rmApp() puts the switches above the app; move them into the floating bar so the app fills the window */
const bar = document.querySelector('.pv-bar');
app.querySelectorAll('.cr-switch').forEach(x => bar.appendChild(x));
function applyRoleState(root) {
  root.querySelectorAll('[data-only]').forEach(el => { el.hidden = !el.dataset.only.split(' ').includes(root.dataset.role); });
}
bar.addEventListener('click', e => {
  const b = e.target.closest('.seg-item'); if (!b) return;
  b.parentElement.querySelectorAll('.seg-item').forEach(x => { x.classList.remove('active'); x.setAttribute('aria-selected', 'false'); });
  b.classList.add('active'); b.setAttribute('aria-selected', 'true');
  if (b.dataset.crRole) rm.dataset.role = b.dataset.crRole;
  if (b.dataset.crState) rm.dataset.state = b.dataset.crState;
  if (b.dataset.crTime) rm.dataset.time = b.dataset.crTime;
  applyRoleState(rm); rmSync(rm);
});
applyRoleState(rm); rmSync(rm);
"""


def rules(style):
    style = re.sub(r"/\*.*?\*/", "", style, flags=re.S)
    out, i = [], 0
    while True:
        j = style.find("{", i)
        if j < 0:
            return out
        depth, k = 1, j + 1
        while depth and k < len(style):
            depth += (style[k] == "{") - (style[k] == "}")
            k += 1
        out.append(style[i:k].strip())
        i = k


def build():
    s = SHOWCASE.read_text(encoding="utf-8")
    style = s[s.index("<style>") + 7:s.index("</style>")]
    css = "\n".join(r for r in rules(style) if KEEP.match(r))
    a = s.index("/* ---------------------------- Remake slice: Home and Stream (desktop)")
    js = s[s.index("const CR_CLASSES = ["):s.index("/* data-only=\"learner\"")]
    js += s[s.index("function crSwitch("):s.index("const CR_VIEWS")]
    js += "const CR_VIEWS = [['learner', 'Learner'], ['teacher', 'Teacher']];\n"
    js += s[a:s.index("/* ---------------------------- Screen previews", a)]
    b = s.index("/* Remake slice: Home and Stream behave like a small app")
    js += s[b:s.index("/* ---------- Boot ---------- */", b)]
    return f"""<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>L.A.R.A. Prototype: Home, Stream and Quiz</title>
  <link rel="icon" href="data:,">
  <!-- Generated by scripts/build_prototype.py from design-system/showcase.html. Do not edit by hand. -->
  <link rel="stylesheet" href="../design-system/assets/fonts/fonts.css">
  <link rel="stylesheet" href="../design-system/assets/phosphor/phosphor.css">
  <link rel="stylesheet" href="../design-system/tokens.css">
  <style>
{css}
{EXTRA_CSS}  </style>
</head>
<body>
<div id="app"></div>
<div class="pv-bar" role="group" aria-label="Prototype controls"></div>
<script>
{js}{BOOT}</script>
</body>
</html>
"""


if __name__ == "__main__":
    page = build()
    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != page:
            sys.exit("prototype/index.html is stale: run python3 scripts/build_prototype.py")
    else:
        OUT.write_text(page, encoding="utf-8")
        print(f"wrote {OUT.relative_to(ROOT)} ({len(page)} bytes)")
